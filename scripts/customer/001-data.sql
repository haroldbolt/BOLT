
CREATE TABLE IF NOT EXISTS customer_schema (id integer PRIMARY KEY CHECK(id=1), version integer NOT NULL, migrated_at timestamptz NOT NULL DEFAULT now());
CREATE TABLE IF NOT EXISTS customer_data (user_id text PRIMARY KEY REFERENCES customer_user(id) ON DELETE CASCADE, revision integer NOT NULL DEFAULT 0, payload jsonb NOT NULL DEFAULT '{}'::jsonb, updated_at timestamptz NOT NULL DEFAULT now());
CREATE TABLE IF NOT EXISTS customer_order_links (order_id text PRIMARY KEY, user_id text NOT NULL REFERENCES customer_user(id) ON DELETE CASCADE, linked_at timestamptz NOT NULL DEFAULT now(), evidence text NOT NULL CHECK(evidence='guest-capability'));
CREATE INDEX IF NOT EXISTS customer_order_links_user ON customer_order_links(user_id);
CREATE TABLE IF NOT EXISTS customer_imports (user_id text REFERENCES customer_user(id) ON DELETE CASCADE, import_id text NOT NULL, created_at timestamptz NOT NULL DEFAULT now(), PRIMARY KEY(user_id,import_id));
CREATE TABLE IF NOT EXISTS customer_audit (id text PRIMARY KEY, subject_hash text NOT NULL, event text NOT NULL, evidence jsonb NOT NULL, created_at timestamptz NOT NULL DEFAULT now());
CREATE TABLE IF NOT EXISTS customer_deletions (user_id text PRIMARY KEY, status text NOT NULL CHECK(status IN ('PENDING_PROVIDER','COMPLETED')), requested_at timestamptz NOT NULL DEFAULT now(), completed_at timestamptz);
CREATE TABLE IF NOT EXISTS customer_mail (id text PRIMARY KEY, encrypted_payload text NOT NULL, recipient_hash text NOT NULL, attempts integer NOT NULL DEFAULT 0, next_attempt timestamptz NOT NULL DEFAULT now(), created_at timestamptz NOT NULL DEFAULT now());
