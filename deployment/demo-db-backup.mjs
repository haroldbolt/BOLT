import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { createHash, randomUUID } from 'node:crypto';
import { spawnSync } from 'node:child_process';

const defaultBin = '/usr/lib/postgresql/18/bin';
const baseEnv = { PATH: '/usr/bin:/bin', LC_ALL: 'C', PGCONNECT_TIMEOUT: '10' };
const requiredArchiveEntries = ['TABLE DATA public customer_schema', 'TABLE DATA public customer_user', 'TABLE DATA public customer_data'];

function pg(bin, tool, args, env = {}, { stdin = 'ignore', capture = false, identity = {} } = {}) {
  const result = spawnSync(path.join(bin, tool), args, {
    env: { ...baseEnv, ...env },
    stdio: [stdin, capture ? 'pipe' : 'ignore', 'ignore'],
    encoding: 'utf8', maxBuffer: 4 * 1024 * 1024, ...identity,
  });
  // PostgreSQL and its child utilities can include private values in stderr/argv.
  if (result.error || result.status !== 0) throw Error('DEMO_DB_BACKUP_' + tool.toUpperCase() + '_FAILED');
  return capture ? result.stdout.trim() : undefined;
}

function serverIdentity() {
  if (process.getuid() !== 0) return {};
  const numeric = flag => {
    const value = spawnSync('/usr/bin/id', [flag, 'postgres'], { encoding: 'utf8', env: baseEnv });
    const id = Number(value.stdout?.trim());
    if (value.status !== 0 || !Number.isSafeInteger(id) || id <= 0) throw Error('DEMO_DB_BACKUP_LOCAL_IDENTITY_MISSING');
    return id;
  };
  return { uid: numeric('-u'), gid: numeric('-g') };
}

// One throwaway, socket-only cluster; the database child process never receives a remote service URL.
export async function withTemporaryPostgres(check, postgresBin = defaultBin) {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'bolt-pg-'));
  const data = path.join(directory, 'data');
  const log = path.join(directory, 'postgres.log');
  const identity = serverIdentity();
  const local = { PGHOST: directory, PGPORT: '5432', PGUSER: 'postgres', PGDATABASE: 'postgres' };
  let started = false;
  try {
    if (identity.uid !== undefined) fs.chownSync(directory, identity.uid, identity.gid);
    pg(postgresBin, 'initdb', ['-D', data, '--username=postgres', '--encoding=UTF8', '--no-locale', '--auth-local=trust', '--auth-host=reject'], {}, { identity });
    // Paths are generated by the process. Quote PostgreSQL literals rather than interpolating shell options.
    const socketDir = directory.replaceAll("'", "''");
    fs.appendFileSync(path.join(data, 'postgresql.conf'),
      "\nlisten_addresses=''\nunix_socket_directories='" + socketDir + "'\nunix_socket_permissions=0700\nshared_buffers=8MB\nmax_connections=10\nlogging_collector=off\n");
    pg(postgresBin, 'pg_ctl', ['-D', data, '-l', log, '-w', '-t', '30', 'start'], {}, { identity });
    started = true;
    return await check(local, (tool, args, env = local, opts) => pg(postgresBin, tool, args, env, opts));
  } finally {
    if (started || fs.existsSync(path.join(data, 'postmaster.pid'))) {
      pg(postgresBin, 'pg_ctl', ['-D', data, '-m', 'immediate', '-w', '-t', '30', 'stop'], {}, { identity });
    }
    fs.rmSync(directory, { recursive: true, force: true });
  }
}

function databaseEnv(connectionString) {
  const url = new URL(connectionString);
  const env = {
    PGUSER: decodeURIComponent(url.username),
    PGPASSWORD: decodeURIComponent(url.password),
    PGDATABASE: decodeURIComponent(url.pathname.slice(1)), PGHOST: decodeURIComponent(url.hostname),
    PGPORT: url.port || '5432',
  };
  // Preserve transport security options without giving libpq a second, conflicting host or database.
  for (const [key, value] of url.searchParams) {
    if (!['sslmode', 'sslrootcert', 'sslcert', 'sslkey', 'sslcrl', 'channel_binding', 'sslnegotiation'].includes(key)) {
      throw Error('DEMO_DB_BACKUP_CONNECTION_OPTION_UNSUPPORTED');
    }
    env['PG' + key.toUpperCase()] = value;
  }
  if (env.PGUSER !== 'bolt_customer_app' || env.PGDATABASE !== 'bolt_customers_demo') throw Error('DEMO_DB_BACKUP_WRONG_TARGET');
  return env;
}

export async function verifyArchive(file, postgresBin = defaultBin) {
  const listing = pg(postgresBin, 'pg_restore', ['--list', file], {}, { capture: true });
  if (!requiredArchiveEntries.every(table => listing.includes(table))) throw Error('DEMO_DB_BACKUP_TABLES_MISSING');
  await withTemporaryPostgres((local, run) => {
    run('psql', ['-X', '--no-password', '-v', 'ON_ERROR_STOP=1', '-c', 'CREATE ROLE bolt_customer_app NOSUPERUSER NOCREATEDB NOCREATEROLE NOBYPASSRLS']);
    run('createdb', ['--no-password', '--owner=bolt_customer_app', 'bolt_customers_demo']);
    const target = { ...local, PGDATABASE: 'bolt_customers_demo' };
    run('pg_restore', ['--no-password', '--exit-on-error', '--single-transaction', '--dbname=bolt_customers_demo', file], target);
    const version = run('psql', ['-XAt', '--no-password', '-v', 'ON_ERROR_STOP=1', '-c',
      'SELECT version FROM public.customer_schema WHERE id=1'], target, { capture: true });
    if (version !== '1') throw Error('DEMO_DB_BACKUP_RESTORED_SCHEMA_MISMATCH');
  }, postgresBin);
}

export async function backupDemoDatabase({ connectionString, directory, postgresBin = defaultBin }) {
  const db = databaseEnv(connectionString);
  fs.mkdirSync(directory, { recursive: true, mode: 0o700 });
  if (!fs.lstatSync(directory).isDirectory()) throw Error('DEMO_DB_BACKUP_DIRECTORY_INVALID');
  fs.chmodSync(directory, 0o700);
  const file = path.join(directory, 'customer-v1-' + randomUUID() + '.dump');
  const partial = file + '.partial';
  const fd = fs.openSync(partial, 'wx', 0o600);
  fs.closeSync(fd);
  try {
    pg(postgresBin, 'pg_dump', ['--no-password', '--format=custom', '--file=' + partial], db);
    await verifyArchive(partial, postgresBin);
    const hash = createHash('sha256');
    for await (const chunk of fs.createReadStream(partial)) hash.update(chunk);
    const sha256 = hash.digest('hex');
    const archiveFd = fs.openSync(partial, 'r');
    try { fs.fsyncSync(archiveFd); } finally { fs.closeSync(archiveFd); }
    fs.renameSync(partial, file);
    const dirFd = fs.openSync(directory, 'r');
    try { fs.fsyncSync(dirFd); } finally { fs.closeSync(dirFd); }
    console.log('[Demo DB] Copia completa v1 verificada mediante restauración aislada.');
    return { file, sha256 };
  } finally {
    fs.rmSync(partial, { force: true });
  }
}
